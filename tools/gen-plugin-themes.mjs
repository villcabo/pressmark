#!/usr/bin/env node
/**
 * Generates src/themes.generated.ts with the theme packs embedded.
 *
 * This is the plugin's equivalent of go:embed, for the same reason: themes/ is
 * the source of truth, and each consumer takes its own copy at build time.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const T = join(ROOT, "themes");

const packs = {};
for (const id of readdirSync(T).sort()) {
  const d = join(T, id);
  if (!statSync(d).isDirectory()) continue;
  packs[`${id}/theme.json`] = readFileSync(join(d, "theme.json"), "utf8");
  packs[`${id}/theme.css`] = readFileSync(join(d, "theme.css"), "utf8");
}

// The sample documents the theme designer previews. Bundled for the same
// reason as the packs: a preview with nothing to show is not a preview.
const samples = {};
const samplesDir = join(ROOT, "samples");
for (const f of readdirSync(samplesDir).sort()) {
  if (!f.endsWith(".md")) continue;
  samples[f.replace(/\.md$/, "")] = readFileSync(join(samplesDir, f), "utf8");
}

const out = `// GENERATED BY tools/gen-plugin-themes.mjs — DO NOT EDIT BY HAND.
// Source: themes/ and samples/ at the repo root. Regenerate with \`make sync-themes\`.
export const EMBEDDED: Record<string, string> = ${JSON.stringify(packs, null, 2)};

export const SAMPLES: Record<string, string> = ${JSON.stringify(samples, null, 2)};
`;
writeFileSync(join(ROOT, "src/themes.generated.ts"), out);
console.log(
  `embedded -> src/themes.generated.ts (${Object.keys(packs).length / 2} packs, ${Object.keys(samples).length} samples)`,
);
